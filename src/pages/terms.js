/**
 * בונה את דף תנאי השימוש.
 * @returns {string}
 */
export function getTermsMarkup() {
  return wrapInLegalShell({
    title: 'תנאי שימוש',
    backHref: LOGIN_PAGE,
    backLabel: 'חזרה להתחברות',
    content: getTermsContentMarkup(),
  });
}
