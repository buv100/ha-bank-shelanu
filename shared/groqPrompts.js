/**
 * בונה מערך messages ל־Groq: system prompt + היסטוריה מסוננת/חתוכה + הודעת המשתמש עם הקשר.
 * @param {{
 *   systemPrompt: string,
 *   history: Array<{ role: string, content: string }>,
 *   modeNote: string,
 *   factsBlock: string,
 *   message: string,
 *   historyLimit?: number
 * }} input
 * @returns {Array<{ role: string, content: string }>}
 */
export function buildGroqMessages(input) {
  const historyLimit = input.historyLimit || 12;

  return [
    { role: 'system', content: input.systemPrompt },
    ...input.history
      .filter((item) => item.role === 'user' || item.role === 'assistant')
      .slice(-historyLimit)
      .map((item) => ({
        role: item.role === 'assistant' ? 'assistant' : 'user',
        content: String(item.content || '').slice(0, 2000),
      })),
    {
      role: 'user',
      content: `${input.modeNote}\n\n${input.factsBlock}\n\nהודעת המשתמש:\n${String(input.message || '').slice(0, 800)}`,
    },
  ];
}
